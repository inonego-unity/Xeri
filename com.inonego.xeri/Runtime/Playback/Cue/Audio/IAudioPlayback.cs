namespace inonego.Xeri.Playback
{
    // ============================================================
    /// <summary>
    /// 제어 가능한 단일 Audio Cue Playback.
    /// </summary>
    // ============================================================
    public interface IAudioPlayback : ICuePlayback
    {
    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// 실제 Audio 재생 위치와 상태를 조회하는 Clock.
        /// </summary>
        // ------------------------------------------------------------
        IPlaybackClock Clock { get; }

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 위치를 보존하고 Audio Playback을 일시정지한다.
        /// </summary>
        // ------------------------------------------------------------
        void Pause();

        // ------------------------------------------------------------
        /// <summary>
        /// 일시정지된 Audio Playback을 같은 위치에서 재개한다.
        /// </summary>
        // ------------------------------------------------------------
        void Resume();

    #endregion

    }
}
