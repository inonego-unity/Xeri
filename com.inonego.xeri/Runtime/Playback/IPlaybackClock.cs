namespace inonego.Xeri.Playback
{
    // ============================================================
    /// <summary>
    /// 재생 상태와 위치를 제공하는 읽기 전용 Clock 계약.
    /// </summary>
    // ============================================================
    public interface IPlaybackClock
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 재생 상태.
        /// </summary>
        // ------------------------------------------------------------
        PlaybackState State { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 재생 중인지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsPlaying { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 일시정지 중인지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsPaused { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 재생 위치.
        /// </summary>
        // ------------------------------------------------------------
        float Time { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 전체 재생 길이.
        /// </summary>
        // ------------------------------------------------------------
        float Duration { get; }
    }
}
