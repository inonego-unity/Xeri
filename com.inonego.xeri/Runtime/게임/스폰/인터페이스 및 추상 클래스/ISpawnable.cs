using System;

namespace inonego.Xeri.Game
{
    // ============================================================
    /// <summary>
    /// 스폰 등록 가능한 객체를 위한 인터페이스입니다.
    /// </summary>
    /// <typeparam name="TKey">스폰 등록 가능한 객체의 키 타입입니다.</typeparam>
    // ============================================================
    public interface ISpawnRegistryObject<TKey> : IKeyable<TKey>, ISpawnable, IDespawnable
    where TKey : IEquatable<TKey>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 스폰되어 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool IsSpawned
        {
            get; protected internal set;
        }
    }

    // ============================================================
    /// <summary>
    /// 스폰 가능한 객체를 위한 인터페이스입니다.
    /// </summary>
    // ============================================================
    public interface ISpawnable
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 스폰 직전에 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        public void OnPreSpawn();

        // ------------------------------------------------------------
        /// <summary>
        /// 스폰 직후에 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        public void OnSpawn();
    }

    // ============================================================
    /// <summary>
    /// 디스폰 가능한 객체를 위한 인터페이스입니다.
    /// </summary>
    // ============================================================
    public interface IDespawnable
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 디스폰 직전에 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        public void OnPreDespawn();

        // ------------------------------------------------------------
        /// <summary>
        /// 디스폰 직후에 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        public void OnDespawn();

        // ------------------------------------------------------------
        /// <summary>
        /// 레지스트리가 등록한 디스폰 콜백. 외부에서는 확장 메서드 Despawn() 으로 호출한다.
        /// </summary>
        // ------------------------------------------------------------
        protected internal Action DespawnFromRegistry { get; set; }
    }
}
