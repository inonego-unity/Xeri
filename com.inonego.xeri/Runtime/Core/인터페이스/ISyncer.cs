namespace inonego.Xeri
{
    // ============================================================
    /// <summary>
    /// 이전 객체의 지원 상태를 다음 객체에 동기화하는 인터페이스.
    /// </summary>
    // ============================================================
    public interface ISyncer<in T>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// Prev와 Next 사이에서 지원하는 상태 동기화를 시도한다.
        /// </summary>
        // ------------------------------------------------------------
        public bool TrySync(T prev, T next);
    }
}
