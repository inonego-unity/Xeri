# 설명
Entity 모델을 Unity Actor로 표현하기 위한 인터페이스 모음.

- IReadOnlyEntityActor : 외부 노출용. Entity·Key·binding 상태를 읽기 전용으로 노출한다.
- IEntityActor         : 시스템 내부용. 변경 가능한 Entity 노출을 제공한다.
========================================================================= BLOCK_HEADER_END */

namespace inonego.Xeri.Game
{
    // ============================================================
    /// <summary>
    /// Entity Actor 읽기 전용 인터페이스.
    /// </summary>
    // ============================================================
    public interface IReadOnlyEntityActor : IKeyable<ulong>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 대응되는 논리 엔티티.
        /// </summary>
        // ------------------------------------------------------------
        IReadOnlyEntity Entity { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 Actor가 Entity에 연결되어 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsBound { get; }
    }

    // ============================================================
    /// <summary>
    /// Entity Actor 시스템 내부 인터페이스.
    /// </summary>
    // ============================================================
    public interface IEntityActor : IReadOnlyEntityActor
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 대응되는 논리 엔티티.
        /// </summary>
        // ------------------------------------------------------------
        new IEntity Entity { get; }
    }
}
