namespace inonego.Xeri
{
    // ============================================================
    /// <summary>
    /// 대상 값이 필터 조건에 맞는지 판별하는 인터페이스.
    /// </summary>
    // ============================================================
    public interface IFilter<in T>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 값이 필터 조건에 맞는지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        public bool IsMatch(T value);
    }
}
