# 설명
객체의 값 상태를 구조체로 기록하고 그 값으로 되돌리는 스냅샷 계약을 정의한다.
Capture는 힙 할당 없이 현재 값을 기록하고, RestoreFrom은 변경 알림 없이 기록한 값으로 되돌린다.

# 제약사항
스냅샷은 값만 담으며 이벤트 구독과 객체 정체성은 기록하지 않는다.
하위 요소가 있으면 상위가 하위의 Capture 결과를 자기 스냅샷에 담는 방식으로 직접 잇는다.
크기가 바뀌는 컬렉션처럼 사본이 필요한 하위에는 IDeepCloneable을 쓴다.
