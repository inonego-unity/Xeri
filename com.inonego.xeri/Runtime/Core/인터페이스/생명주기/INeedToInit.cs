namespace inonego.Xeri
{
    // ============================================================
    /// <summary>
    /// 초기화·해제가 필요한 객체를 위한 인터페이스입니다.
    /// </summary>
    // ============================================================
    public interface INeedToInit
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 초기화를 수행합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void Init();

        // ------------------------------------------------------------
        /// <summary>
        /// 해제를 수행합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void Release();
    }

    // ============================================================
    /// <summary>
    /// 파라미터와 함께 초기화·해제가 필요한 객체를 위한 인터페이스입니다.
    /// </summary>
    // ============================================================
    public interface INeedToInit<TParam>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 파라미터를 받아 초기화를 수행합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void Init(TParam param);

        // ------------------------------------------------------------
        /// <summary>
        /// 해제를 수행합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void Release();
    }
}
