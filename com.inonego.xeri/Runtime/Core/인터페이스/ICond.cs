namespace inonego.Xeri
{
    // ============================================================
    /// <summary>
    /// 지정한 Context에서 요구 충족 여부를 판정하는 인터페이스.
    /// </summary>
    // ============================================================
    public interface ICond<in TContext>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 Context에서 요구를 충족하는지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        public bool Check(TContext context);
    }
}
