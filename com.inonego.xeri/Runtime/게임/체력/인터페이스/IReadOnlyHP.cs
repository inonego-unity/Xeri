using System;

namespace inonego.Xeri.Game
{

    // ============================================================
    /// <summary>
    /// HP 읽기 전용 뷰 인터페이스 (값 타입 무관, 상태만).
    /// </summary>
    // ============================================================
    public interface IReadOnlyHP
    {

    #region 이벤트

        // ------------------------------------------------------------
        /// <summary>
        /// 상태(생/사)가 변경될 때 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        event ValueChangeEventHandler<HPState> OnStateChange;

    #endregion

    #region 프로퍼티

        // ------------------------------------------------------------
        /// <summary>
        /// 생존 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsAlive { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 사망 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsDead { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 상태(생/사).
        /// </summary>
        // ------------------------------------------------------------
        HPState Current { get; }

    #endregion

    }

    // ============================================================
    /// <summary>
    /// HP 읽기 전용 뷰 인터페이스 (값 포함).
    /// </summary>
    // ============================================================
    public interface IReadOnlyHP<TValue> : IReadOnlyHP
    {

    #region 이벤트

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 체력 값이 변경될 때 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        event ValueChangeEventHandler<TValue> OnValueChange;

        // ------------------------------------------------------------
        /// <summary>
        /// 최대 체력 값이 변경될 때 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        event ValueChangeEventHandler<TValue> OnMaxValueChange;

        // ------------------------------------------------------------
        /// <summary>
        /// 힐이 적용되었을 때 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        event EventHandler<HPApplyEventArgs<TValue>> OnHeal;

        // ------------------------------------------------------------
        /// <summary>
        /// 데미지가 적용되었을 때 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        event EventHandler<HPApplyEventArgs<TValue>> OnDamage;

    #endregion

    #region 프로퍼티

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 체력 값.
        /// </summary>
        // ------------------------------------------------------------
        TValue Value { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 최대 체력 값.
        /// </summary>
        // ------------------------------------------------------------
        TValue MaxValue { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 체력 비율 (0.0 ~ 1.0)
        /// </summary>
        // ------------------------------------------------------------
        float Ratio { get; }

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 비율과 기준에 따라 적용할 양을 계산한다.
        /// </summary>
        // ------------------------------------------------------------
        TValue CalculateApplyAmount(float ratio, HPApplyRatioType applyRatioType);

    #endregion

    }

    // ============================================================
    /// <summary>
    /// int 기반 HP 읽기 전용 인터페이스.
    /// </summary>
    // ============================================================
    public interface IReadOnlyHP_I : IReadOnlyHP<int> { }

    // ============================================================
    /// <summary>
    /// float 기반 HP 읽기 전용 인터페이스.
    /// </summary>
    // ============================================================
    public interface IReadOnlyHP_F : IReadOnlyHP<float> { }

}
