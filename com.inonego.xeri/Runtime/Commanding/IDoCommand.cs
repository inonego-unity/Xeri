namespace inonego.Xeri.Commanding
{
    // ============================================================
    /// <summary>
    /// 실행과 실행 취소가 가능한 명령의 공통 계약.
    /// </summary>
    // ============================================================
    public interface IDoCommand
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 명령을 실행한다.
        /// </summary>
        // ------------------------------------------------------------
        void Do();

        // ------------------------------------------------------------
        /// <summary>
        /// 실행한 명령을 되돌린다.
        /// </summary>
        // ------------------------------------------------------------
        void Undo();

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 명령을 실행 취소할 수 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool CanUndo { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 명령을 설명하는 문자열.
        /// </summary>
        // ------------------------------------------------------------
        string Desc { get; }
    }
}
