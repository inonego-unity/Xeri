using UnityEngine;

namespace inonego.Xeri
{
    // ======================================================================
    /// <summary>
    /// 게임 오브젝트를 생성하여 가져오거나 반환하도록 도와주는 인터페이스입니다.
    /// </summary>
    // ======================================================================
    public interface IGameObjectProvider
    {

    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// <br/> 게임 오브젝트를 생성할 위치입니다.
        /// <br/> null인 경우, 루트에 생성됩니다.
        /// </summary>
        // ------------------------------------------------------------
        public Transform Parent { get; set; }

    #endregion

    #region 메서드

        // ----------------------------------------------------------------------
        /// <summary>
        /// <br/> 게임 오브젝트를 가져옵니다.
        /// <br/> 반환 시 활성 상태는 Provider 구현과 공급 원본의 설정을 따릅니다.
        /// </summary>
        // ----------------------------------------------------------------------
        public GameObject Acquire(bool worldPositionStays = true);

        // --------------------------------------------------------------------------------
        /// <summary>
        /// <br/> 게임 오브젝트를 비동기로 가져옵니다.
        /// <br/> 정상 완료 시 유효한 GameObject를 반환합니다.
        /// <br/> 동일 Provider의 여러 비동기 획득 요청은 서로 독립적으로 처리됩니다.
        /// <br/> 반환 시 활성 상태는 Provider 구현과 공급 원본의 설정을 따릅니다.
        /// </summary>
        // --------------------------------------------------------------------------------
        public Awaitable<GameObject> AcquireAsync(bool worldPositionStays = true);

        // --------------------------------------------------------------------------------
        /// <summary>
        /// <br/> 이 Provider에서 획득한 유효한 게임 오브젝트의 반환을 한 번 시도합니다.
        /// <br/> 호출자의 반환 책임은 호출과 함께 종료되며, 예외가 발생해도 같은 인스턴스를 재시도하지 않습니다.
        /// <br/> 예외는 Provider가 반환 처리를 완료하지 못했음을 호출자에게 전달합니다.
        /// </summary>
        // --------------------------------------------------------------------------------
        public void Release(GameObject go, bool worldPositionStays = true);

    #endregion

    }
}
