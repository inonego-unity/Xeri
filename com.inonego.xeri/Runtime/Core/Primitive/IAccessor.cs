using System;

namespace inonego.Xeri.Primitive
{

    // ============================================================
    /// <summary>
    /// 값 읽기 접근자 인터페이스
    /// </summary>
    // ============================================================
    public interface IValueGetter<T>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 값 반환
        /// </summary>
        // ------------------------------------------------------------
        T Get();
    }

    // ============================================================
    /// <summary>
    /// 값 쓰기 접근자 인터페이스
    /// </summary>
    // ============================================================
    public interface IValueSetter<T>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 값 설정
        /// </summary>
        // ------------------------------------------------------------
        void Set(T value);
    }

}
