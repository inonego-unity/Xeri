namespace inonego.Xeri.UI.TableGrid
{

    #region 구성

    // ============================================================
    /// <summary>
    /// 데이터를 바꾸는 동작을 허용하는지 나타낸다.
    /// </summary>
    // ============================================================
    public enum TableGridAccess
    {
        ReadOnly,
        Editable
    }

    // ================================================================================
    /// <summary>
    /// <br/> 표가 제공하는 도구 수준을 나타낸다.
    /// <br/> List는 헤더 클릭 정렬, Workspace는 열 메뉴·필터 편집·열 패널·빠른 이동.
    /// </summary>
    // ================================================================================
    public enum TableGridTools
    {
        List,
        Workspace
    }

    // ============================================================
    /// <summary>
    /// 선택 방식을 나타낸다.
    /// </summary>
    // ============================================================
    public enum TableGridSelectionMode
    {
        None,
        Row,
        MultiRow,
        Cell
    }

    #endregion

    #region 표시 모드

    // ================================================================================
    /// <summary>
    /// <br/> 행을 넘겨 보는 방식을 나타낸다.
    /// <br/> Scroll은 전체 가상화 스크롤, Paged는 같은 본문에 한 페이지 구간만 보인다.
    /// </summary>
    // ================================================================================
    public enum TableGridNavigation
    {
        Scroll,
        Paged
    }

    #endregion

    #region 행 이동

    // ============================================================
    /// <summary>
    /// 옮긴 행을 기준 행의 앞에 넣을지 뒤에 넣을지 나타낸다.
    /// </summary>
    // ============================================================
    public enum TableGridMovePlacement
    {
        Before,
        After
    }

    // ======================================================================
    /// <summary>
    /// <br/> 행 이동 요청을 만든 입력을 나타낸다.
    /// <br/> ApplySort는 지금 보기 정렬 순서를 데이터에 적용해 달라는 요청이다.
    /// </summary>
    // ======================================================================
    public enum TableGridMoveSource
    {
        Drag,
        Keyboard,
        Menu,
        Cut,
        ApplySort
    }

    // ======================================================================
    /// <summary>
    /// 새 행을 넣을 자리를 나타낸다. End는 끝, Before·After는 기준 행의 앞·뒤다.
    /// </summary>
    // ======================================================================
    public enum TableGridAddPosition
    {
        End,
        Before,
        After
    }

    #endregion

    #region 테마

    // ======================================================================
    /// <summary>
    /// 표 테마를 나타낸다. Default는 표 자체 팔레트, Editor는 Unity 에디터 색이다.
    /// </summary>
    // ======================================================================
    public enum TableGridTheme
    {
        Default,
        Editor
    }

    // ================================================================================
    /// <summary>
    /// Default 테마의 다크·라이트를 나타낸다. Auto는 패널 종류와 Unity 스킨에서 정한다.
    /// </summary>
    // ================================================================================
    public enum TableGridColorMode
    {
        Auto,
        Dark,
        Light
    }

    #endregion

    #region 행 및 선택

    // ============================================================
    /// <summary>
    /// 표시 행의 범용 역할을 나타낸다.
    /// </summary>
    // ============================================================
    public enum TableGridRowKind
    {
        Data,
        GroupHeader,
        Summary
    }

    // ============================================================
    /// <summary>
    /// 선택 상태가 대상으로 삼는 단위를 나타낸다.
    /// </summary>
    // ============================================================
    public enum TableGridSelectionKind
    {
        None,
        Cell,
        Row,
        Column
    }

    #endregion

    #region 셀 편집

    // ================================================================================
    /// <summary>
    /// <br/> 열의 셀 편집 방식을 나타낸다.
    /// <br/> None은 보기만, Editor는 편집기, Inline은 셀 안 컨트롤, Detail은 셀 밖 편집이다.
    /// </summary>
    // ================================================================================
    public enum TableGridCellEditKind
    {
        None,
        Editor,
        Inline,
        Detail
    }

    // ================================================================================
    /// <summary>
    /// <br/> Inline 셀의 반영 시점을 나타낸다.
    /// <br/> Immediate는 값을 바꿀 때마다, Confirm은 확정(Enter·포커스 이탈) 때 요청한다.
    /// </summary>
    // ================================================================================
    public enum TableGridInlineCommit
    {
        Immediate,
        Confirm
    }

    // ======================================================================
    /// <summary>
    /// 편집기를 놓을 자리를 나타낸다. InCell은 셀 안, Popup은 셀 위에 띄운다.
    /// </summary>
    // ======================================================================
    public enum TableGridEditorPlacement
    {
        InCell,
        Popup
    }

    #endregion

    #region 표시 및 정렬

    // ============================================================
    /// <summary>
    /// 셀 콘텐츠의 가로 정렬을 나타낸다.
    /// </summary>
    // ============================================================
    public enum TableGridAlignment
    {
        Left,
        Center,
        Right
    }

    // ============================================================
    /// <summary>
    /// 정렬 intent의 방향을 나타낸다.
    /// </summary>
    // ============================================================
    public enum TableGridSortDirection
    {
        Ascending,
        Descending
    }

    #endregion

}
