using System;

using TValue = System.Single;

namespace inonego.Xeri.Utility
{
    // ============================================================
    /// <summary>
    /// 타이머 인터페이스.
    /// </summary>
    // ============================================================
    public interface ITimer : IReadOnlyTimer
    {

    #region 시간

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머 지속 시간.
        /// </summary>
        // ------------------------------------------------------------
        public new TValue Duration { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// <br/> 타이머가 경과한 시간.
        /// <br/> 중지 후에도 Reset 또는 Start 전까지 값이 유지된다.
        /// </summary>
        // ------------------------------------------------------------
        public new TValue ElapsedTime { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// <br/> 타이머의 남은 시간.
        /// <br/> 중지 후에도 Reset 또는 Start 전까지 값이 유지된다.
        /// </summary>
        // ------------------------------------------------------------
        public new TValue RemainingTime { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// Start 시 사용할 duration 값. Stop/Reset 후에도 유지된다.
        /// </summary>
        // ------------------------------------------------------------
        internal TValue cached { get; set; }

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머를 업데이트한다.
        /// </summary>
        // ------------------------------------------------------------
        public void Tick(TValue deltaTime);

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머 작동을 시작한다.
        /// </summary>
        // ------------------------------------------------------------
        public void Start(TValue duration);

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머 작동을 중지한다.
        /// </summary>
        // ------------------------------------------------------------
        public void Stop();

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머 작동을 일시정지한다.
        /// </summary>
        // ------------------------------------------------------------
        public void Pause();

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머 작동을 재개한다.
        /// </summary>
        // ------------------------------------------------------------
        public void Resume();

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머를 리셋한다.
        /// </summary>
        // ------------------------------------------------------------
        public void Reset();

    #endregion

    }
}
