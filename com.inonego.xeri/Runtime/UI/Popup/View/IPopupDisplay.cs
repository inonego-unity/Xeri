# 특이사항, 제약사항
모든 좌표는 Display가 정한 Y-down 팝업 좌표계이며 소유 패널과의 변환은 Display가 맡는다.
입력 차단과 닫기 정책은 PopupHost가 맡고 Display는 표시 자원과 자체 포커스를 관리한다.
