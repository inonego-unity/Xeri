using System;

namespace inonego.Xeri.Primitive
{

    // ============================================================
    /// <summary>
    /// <br/> Unity C# 11 generic math 미지원을 대체하는 인터페이스.
    /// <br/> 스칼라 수치 타입에 산술·비교·범위·접근자 연산을 추상화한다.
    /// </summary>
    // ============================================================
    public interface INumeric<TSelf, TValue>
        : IEquatable<TSelf>, IComparable<TSelf>,
          IValueGetter<TValue>, IValueSetter<TValue>
    where TSelf : INumeric<TSelf, TValue>
    {

    #region 사칙연산

        // ------------------------------------------------------------
        /// <summary>
        /// 덧셈
        /// </summary>
        // ------------------------------------------------------------
        TSelf Add(TSelf other);

        // ------------------------------------------------------------
        /// <summary>
        /// 뺄셈
        /// </summary>
        // ------------------------------------------------------------
        TSelf Sub(TSelf other);

        // ------------------------------------------------------------
        /// <summary>
        /// 곱셈
        /// </summary>
        // ------------------------------------------------------------
        TSelf Mul(TSelf other);

        // ------------------------------------------------------------
        /// <summary>
        /// 나눗셈
        /// </summary>
        // ------------------------------------------------------------
        TSelf Div(TSelf other);

        // ------------------------------------------------------------
        /// <summary>
        /// 나머지
        /// </summary>
        // ------------------------------------------------------------
        TSelf Mod(TSelf other);

    #endregion

    #region 수치 연산

        // ------------------------------------------------------------
        /// <summary>
        /// 부호 반전
        /// </summary>
        // ------------------------------------------------------------
        TSelf Negate();

        // ------------------------------------------------------------
        /// <summary>
        /// 절댓값
        /// </summary>
        // ------------------------------------------------------------
        TSelf Abs();

        // ------------------------------------------------------------
        /// <summary>
        /// 양수 여부
        /// </summary>
        // ------------------------------------------------------------
        bool IsPositive { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 음수 여부
        /// </summary>
        // ------------------------------------------------------------
        bool IsNegative { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 0 여부
        /// </summary>
        // ------------------------------------------------------------
        bool IsZero { get; }

    #endregion

    #region 범위

        // ------------------------------------------------------------
        /// <summary>
        /// 두 값 중 작은 값 반환
        /// </summary>
        // ------------------------------------------------------------
        TSelf Min(TSelf other);

        // ------------------------------------------------------------
        /// <summary>
        /// 두 값 중 큰 값 반환
        /// </summary>
        // ------------------------------------------------------------
        TSelf Max(TSelf other);

        // ------------------------------------------------------------
        /// <summary>
        /// 값을 [min, max] 범위로 제한
        /// </summary>
        // ------------------------------------------------------------
        TSelf Clamp(TSelf min, TSelf max);

    #endregion

    #region 변환

        // ------------------------------------------------------------
        /// <summary>
        /// float 으로 변환한다.
        /// </summary>
        // ------------------------------------------------------------
        float ToFloat();

        // ------------------------------------------------------------
        /// <summary>
        /// float 으로부터 TSelf 를 생성한다.
        /// </summary>
        // ------------------------------------------------------------
        TSelf FromFloat(float value);

    #endregion

    }

}
