using System;

using inonego;
using inonego.Xeri;

namespace inonego.Xeri.Serializable
{
    // ============================================================
    /// <summary>
    /// 값을 수정하고 상태 변경을 알리는 수정자 인터페이스.
    /// </summary>
    // ============================================================
    public interface IModifier<T> : IDeepCloneable<IModifier<T>>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// Modify 결과에 영향을 주는 내부 상태가 변경된 뒤 발생한다.
        /// </summary>
        // ------------------------------------------------------------
        event Action OnChange;

        // ----------------------------------------------------------------------
        /// <summary>
        /// <br/> 결과가 입력 값과 무관한지(입력을 덮어쓰는지) 반환한다.
        /// <br/> true면 앞서 적용된 수정 결과를 무시해도 결과가 같음을 보장한다.
        /// <br/> false는 입력에 의존하거나 이를 보장할 수 없다는 뜻이다.
        /// </summary>
        // ----------------------------------------------------------------------
        public bool Replaces { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 수정자가 값을 수정하여 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        public T Modify(T value);
    }
}
