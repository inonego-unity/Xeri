namespace inonego.Xeri.Game
{
    using Xeri.Serializable;

    // ============================================================
    /// <summary>
    /// 엔티티 읽기 전용 뷰 인터페이스.
    /// </summary>
    // ============================================================
    public interface IReadOnlyEntity : IKeyable<ulong>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 체력 상태(읽기 전용, 값 타입 무관).
        /// </summary>
        // ------------------------------------------------------------
        IReadOnlyHP HP { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 그룹 인덱스(읽기 전용).
        /// </summary>
        // ------------------------------------------------------------
        IReadOnlyValue<int> Group { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// Registry가 관리하는 현재 스폰 처리 상태.
        /// </summary>
        // ------------------------------------------------------------
        SpawnState SpawnState { get; }
    }

    // ==================================================================================
    /// <summary>
    /// 시스템 내부에서 SpawnRegistry 등록과 HP·Group 변경을 허용하는 엔티티 인터페이스.
    /// </summary>
    // ==================================================================================
    public interface IEntity : IReadOnlyEntity, ISpawnRegistryObject<ulong>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 시스템 내부에서 변경할 수 있는 체력. IReadOnlyEntity.HP를 가린다.
        /// </summary>
        // ------------------------------------------------------------
        new IHP HP { get; }

        // ----------------------------------------------------------------------
        /// <summary>
        /// 시스템 내부에서 변경할 수 있는 그룹 인덱스. IReadOnlyEntity.Group을 가린다.
        /// </summary>
        // ----------------------------------------------------------------------
        new IValue<int> Group { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 두 상위 계약의 동일한 스폰 상태를 하나의 읽기 전용 멤버로 노출한다.
        /// </summary>
        // ------------------------------------------------------------
        new SpawnState SpawnState { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 키를 설정한다. 레지스트리 내부에서만 호출.
        /// </summary>
        // ------------------------------------------------------------
        protected internal void SetKey(ulong key);

        // ------------------------------------------------------------
        /// <summary>
        /// 키를 초기화한다. 레지스트리 내부에서만 호출.
        /// </summary>
        // ------------------------------------------------------------
        protected internal void ClearKey();
    }
}
