# 설명
자동 스크롤이 움직일 대상의 계약. UI Toolkit ScrollView, UGUI ScrollRect, 자체 스크롤 영역을 같은 방식으로 다룬다.

# 특이사항, 제약사항
delta는 화면 방향 기준이다. x가 양수면 오른쪽, y가 양수면 아래쪽 내용이 보이도록 움직인다.
