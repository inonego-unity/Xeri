namespace inonego.Xeri.Serializable
{
    // ============================================================
    /// <summary>
    /// Serialized Collection의 구조적 불변식을 복구하는 계약.
    /// </summary>
    // ============================================================
    public interface ISerializedCollectionNormalizer
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 직렬화된 항목을 컬렉션의 정렬 및 중복 제약에 맞게 정규화한다.
        /// </summary>
        // ------------------------------------------------------------
        void NormalizeSerializedState();
    }

    // ======================================================================
    /// <summary>
    /// Serialized 데이터와 Runtime 컬렉션을 명시적으로 동기화하는 내부 계약.
    /// </summary>
    // ======================================================================
    internal interface ISerializedRuntimeCollection
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 Runtime 컬렉션을 직렬화된 저장 항목에 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        void ApplyRuntime();

        // ------------------------------------------------------------
        /// <summary>
        /// 직렬화된 저장 항목을 기준으로 Runtime 컬렉션을 재구성한다.
        /// </summary>
        // ------------------------------------------------------------
        void UpdateRuntime();
    }
}
