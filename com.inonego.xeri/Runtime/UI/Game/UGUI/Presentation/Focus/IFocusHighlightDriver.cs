namespace inonego.Xeri.UI.Game
{
    // ============================================================
    /// <summary>
    /// Focus Highlight 표시 backend 계약.
    /// </summary>
    // ============================================================
    public interface IFocusHighlightDriver
    {
        // ------------------------------------------------------------
        /// <summary>
        /// backend가 현재 표시 요청을 받을 수 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsValid { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 여러 실제 UI 대상의 Highlight 구멍과 입력 차단 정책을 표시한다.
        /// </summary>
        // ------------------------------------------------------------
        void Show(FocusHighlightParams parameters);

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 Focus Highlight를 숨긴다.
        /// </summary>
        // ------------------------------------------------------------
        void Hide();
    }
}
