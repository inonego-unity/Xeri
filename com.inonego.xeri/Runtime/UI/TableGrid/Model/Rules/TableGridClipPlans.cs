# 설명
클립보드·지우기·행 삽입 규칙(TableGridClipboard)이 만드는 계획 형식을 정의한다.
셀 변경 계획(TableGridEditPlan)과 행 삽입 계획(TableGridInsertPlan)은 건너뛴 셀 수와 실패 이유를 공통으로 가진다.

# 특이사항, 제약사항
계획은 데이터를 바꾸지 않고 호스트에 요청할 내용만 담는다.
