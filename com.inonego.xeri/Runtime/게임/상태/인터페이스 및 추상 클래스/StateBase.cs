# 설명
Owner 를 자동 보관하는 IState 추상 베이스 클래스.
StateMachine<TOwner> 에 등록될 때 SetOwner 가 자동 호출되어 자식은 Owner 프로퍼티로 즉시 접근한다.
========================================================================= BLOCK_HEADER_END */

namespace inonego.Xeri.Game
{
    // ============================================================
    /// <summary>
    /// Owner 보관 + IState 구현 추상 베이스.
    /// </summary>
    // ============================================================
    public abstract class StateBase<TOwner> : IState
    {

    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// 상태가 속한 소유자.
        /// </summary>
        // ------------------------------------------------------------
        protected TOwner Owner { get; private set; }

    #endregion

    #region Owner 주입

        // ------------------------------------------------------------
        /// <summary>
        /// StateMachine 등록 시 호출된다(어셈블리 내부 전용).
        /// </summary>
        // ------------------------------------------------------------
        internal void SetOwner(TOwner owner)
        {
            Owner = owner;
        }

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 상태 진입 시 호출된다. 자식이 override 한다.
        /// </summary>
        // ------------------------------------------------------------
        public virtual void OnEnter() {}

        // ------------------------------------------------------------
        /// <summary>
        /// 상태 종료 시 호출된다. 자식이 override 한다.
        /// </summary>
        // ------------------------------------------------------------
        public virtual void OnExit() {}

        // ------------------------------------------------------------
        /// <summary>
        /// 상태 갱신 시 호출된다. 자식이 override 한다.
        /// </summary>
        // ------------------------------------------------------------
        public virtual void OnUpdate() {}

    #endregion

    }
}
