using System;
using System.Collections;
using System.Collections.Generic;

using UnityEditor;

namespace inonego.Xeri.Serializable.Editor
{
    // ============================================================
    /// <summary>
    /// Collection cell의 허용 편집 방식.
    /// </summary>
    // ============================================================
    internal enum CollectionCellEditMode
    {
        Default,
        ReplaceOnly,
        ReadOnly,
    }

    // ============================================================
    /// <summary>
    /// 행 명령의 성공 여부와 최종 선택 가능한 위치를 분리한다.
    /// </summary>
    // ============================================================
    internal readonly struct CollectionRowCommandResult
    {
        public bool Succeeded { get; }
        public int RowIndex { get; }

        private CollectionRowCommandResult(bool succeeded, int rowIndex)
        {
            Succeeded = succeeded;
            RowIndex = rowIndex;
        }

        public static CollectionRowCommandResult Success(int rowIndex)
        {
            return new CollectionRowCommandResult(true, rowIndex);
        }

        public static CollectionRowCommandResult Failure => new CollectionRowCommandResult(false, -1);
    }

    // ============================================================
    /// <summary>
    /// Collection Editor가 사용하는 직렬화 컬렉션 편집 모델 계약.
    /// </summary>
    // ============================================================
    internal interface ICollectionEditorModel
    {

    #region 프로퍼티

        // ------------------------------------------------------------
        /// <summary>
        /// 편집 대상의 직렬화 객체를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        SerializedObject SerializedObject { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 편집 대상 컬렉션의 프로퍼티 경로를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        string CollectionPropertyPath { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 표시 이름을 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        string Label { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 편집 대상의 안내 문구를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        string Description { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 검증 결과를 표시할 열 식별자를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        string ValidationColumnID { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 항목 수를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        int Count { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 행 재정렬 가능 여부를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        bool CanReorder { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 표시할 열 목록을 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        IReadOnlyList<CollectionColumnSpec> Columns { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 컬렉션의 세션 변경 세대를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        ulong Revision { get; }

    #endregion

    #region 조회

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 편집 대상 컬렉션의 프로퍼티를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        SerializedProperty GetCollectionProperty();

        // ------------------------------------------------------------
        /// <summary>
        /// 주어진 프로퍼티를 대상으로 편집 모델을 생성한다.
        /// </summary>
        // ------------------------------------------------------------
        ICollectionEditorModel CreateFor(SerializedProperty property);

        // ------------------------------------------------------------
        /// <summary>
        /// 표시할 원본 행의 인덱스를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        IEnumerable<int> GetSourceRows();

        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 행의 식별 값을 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        object GetRowIdentity(int sourceIndex);

        // ------------------------------------------------------------
        /// <summary>
        /// 식별 값과 일치하는 행을 찾고 중복되거나 없으면 -1을 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        int FindRow(object identity);

        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 행의 프로퍼티를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        SerializedProperty GetRowProperty(int sourceIndex);

        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 셀의 프로퍼티를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        SerializedProperty GetCellProperty(int sourceIndex, string columnID);

        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 셀의 편집 방식을 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        CollectionCellEditMode GetCellEditMode(int sourceIndex, string columnID);

        // ------------------------------------------------------------
        /// <summary>
        /// 관리 참조를 추가할 열과 선언 타입을 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        bool TryGetManagedReferenceAddTarget(out string columnID, out Type declaredType);

    #endregion

    #region 검증

        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 행의 검증 메시지를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        string GetRowValidationMessage(int sourceIndex);

        // ------------------------------------------------------------
        /// <summary>
        /// 무효한 직렬화 행의 원본 인덱스를 일괄 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        IReadOnlyList<int> GetInvalidRowIndices();

        // ------------------------------------------------------------
        /// <summary>
        /// 확정된 행 또는 적용 전 후보 값에 대한 진단과 처리 정책을 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        CollectionValidationResult Validate(CollectionValidationContext context);

    #endregion

    #region 행 명령

        // ------------------------------------------------------------
        /// <summary>
        /// 항목을 추가하고 성공 여부와 선택 가능한 위치를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        CollectionRowCommandResult Add(Action<int> initialize = null);

        // ------------------------------------------------------------
        /// <summary>
        /// 항목을 복제하고 성공 여부와 선택 가능한 위치를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        CollectionRowCommandResult DuplicateAt(int sourceIndex);

        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 인덱스의 항목을 삭제한다.
        /// </summary>
        // ------------------------------------------------------------
        void RemoveAt(int sourceIndex);

        // ------------------------------------------------------------
        /// <summary>
        /// 선택한 항목을 한 번의 작업으로 삭제한다.
        /// </summary>
        // ------------------------------------------------------------
        void RemoveMany(IReadOnlyList<int> sourceIndices, string undoName);

        // ------------------------------------------------------------
        /// <summary>
        /// 항목을 이동하고 정규화 후 확인된 행 인덱스를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        int Move(int sourceIndex, int destinationIndex);

        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 행의 붙여넣기를 시도하고 결과 위치와 실패 사유를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        bool TryPasteAt(int sourceIndex, out int resolvedIndex, out string reason);

    #endregion

    #region 변경 상태 동기화

        // ------------------------------------------------------------
        /// <summary>
        /// 실제 컬렉션 변경을 확인하고 공유 세대에 반영했는지 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        bool ObserveExternalChange();

        // ------------------------------------------------------------
        /// <summary>
        /// 직렬화 데이터와 현재 편집 상태를 동기화한다.
        /// </summary>
        // ------------------------------------------------------------
        void Synchronize();

        // ------------------------------------------------------------
        /// <summary>
        /// Undo/Redo로 복원된 owner와 Model 스냅샷을 함께 동기화한다.
        /// </summary>
        // ------------------------------------------------------------
        void RestoreSerializedState();

    #endregion

    #region 변경 확정

        // ------------------------------------------------------------
        /// <summary>
        /// 프로퍼티 변경사항을 반영한다.
        /// </summary>
        // ------------------------------------------------------------
        bool CommitPropertyChange(SerializedProperty property);

        // ------------------------------------------------------------
        /// <summary>
        /// 값 변경사항을 반영한다.
        /// </summary>
        // ------------------------------------------------------------
        void CommitValueChange(string propertyPath);

        // ------------------------------------------------------------
        /// <summary>
        /// 편집한 내용을 대상에 반영한다.
        /// </summary>
        // ------------------------------------------------------------
        void CommitChanges(string propertyPath = null);

    #endregion

    }
}
