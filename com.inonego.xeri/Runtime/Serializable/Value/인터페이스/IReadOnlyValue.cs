namespace inonego.Xeri.Serializable
{
    using Primitive; // inonego.Xeri.Primitive

    // ============================================================
    /// <summary>
    /// Value 읽기 전용 뷰 인터페이스.
    /// </summary>
    // ============================================================
    public interface IReadOnlyValue<T> : IValueGetter<T>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 값.
        /// </summary>
        // ------------------------------------------------------------
        T Base { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 값이 변경될 때 발생하는 이벤트.
        /// </summary>
        // ------------------------------------------------------------
        event ValueChangeEventHandler<T> OnBaseChange;

        // ------------------------------------------------------------
        /// <summary>
        /// IValueGetter 기본 구현. Base를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        T IValueGetter<T>.Get() => Base;
    }
}
