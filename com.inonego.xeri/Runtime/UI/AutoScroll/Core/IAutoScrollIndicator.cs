using UnityEngine;

namespace inonego.Xeri.UI.AutoScroll
{
    // ============================================================
    /// <summary>
    /// 자동 스크롤 표시기.
    /// </summary>
    // ============================================================
    public interface IAutoScrollIndicator
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 기준점에 표시기를 보인다.
        /// </summary>
        // ------------------------------------------------------------
        void Show(Vector2 origin);

        // ------------------------------------------------------------
        /// <summary>
        /// 지금 스크롤 속도(px/s, 화면 방향)로 방향 표시를 바꾼다.
        /// </summary>
        // ------------------------------------------------------------
        void SetVelocity(Vector2 velocity);

        // ------------------------------------------------------------
        /// <summary>
        /// 표시기를 숨긴다.
        /// </summary>
        // ------------------------------------------------------------
        void Hide();
    }
}
