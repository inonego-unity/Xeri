using System;
using System.Collections;
using System.Collections.Generic;

namespace inonego.Xeri.Game
{
    // ============================================================
    /// <summary>
    /// AI 판단 집단의 식별자, 구성원과 종료 상태를 읽기 전용으로 노출한다.
    /// </summary>
    // ============================================================
    public interface IReadOnlyAIGroup
    {

    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// AIGroup을 구분하는 프로젝트 지정 식별자.
        /// </summary>
        // ------------------------------------------------------------
        ulong ID { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 등록된 구성원 수.
        /// </summary>
        // ------------------------------------------------------------
        int MemberCount { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 AIGroup 수명이 종료되었는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsDisposed { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 구성원을 Entity Key 오름차순으로 열거한다.
        /// </summary>
        // ------------------------------------------------------------
        IEnumerable<IReadOnlyEntity> Members { get; }

    #endregion

    #region 이벤트

        // ------------------------------------------------------------
        /// <summary>
        /// AIGroup 수명이 종료된 뒤 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        event Action<IReadOnlyAIGroup> OnDisposed;

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 지정 Entity Key가 현재 구성원인지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        bool ContainsMember(ulong entityKey);

        // ------------------------------------------------------------
        /// <summary>
        /// 지정 Entity Key의 현재 구성원을 찾는다.
        /// </summary>
        // ------------------------------------------------------------
        bool TryFindMember(ulong entityKey, out IReadOnlyEntity member);

    #endregion

    }
}
