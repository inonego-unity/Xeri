namespace inonego.Xeri
{
    // ======================================================================
    /// <summary>
    /// <br/> 현재 값을 구조체 스냅샷으로 기록하고 되돌리는 인터페이스.
    /// <br/> 객체를 복제하는 IDeepCloneable과 달리 새 객체를 만들지 않는다.
    /// </summary>
    /// <typeparam name="TSnapshot">기록하는 값 구조체. 비교가 필요하면 IEquatable을 구현한다.</typeparam>
    // ======================================================================
    public interface ISnapshotable<TSnapshot>
    where TSnapshot : struct
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 값 상태를 힙 할당 없이 스냅샷으로 기록한다.
        /// </summary>
        // ------------------------------------------------------------
        public TSnapshot Capture();

        // ------------------------------------------------------------
        /// <summary>
        /// <br/> 기록한 스냅샷의 값으로 되돌린다.
        /// <br/> 변경 이벤트를 발행하지 않으며 구독은 건드리지 않는다.
        /// </summary>
        // ------------------------------------------------------------
        public void RestoreFrom(in TSnapshot snapshot);
    }
}
