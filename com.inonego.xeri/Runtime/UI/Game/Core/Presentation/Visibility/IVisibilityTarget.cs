namespace inonego.Xeri.UI.Game
{
    // ============================================================
    /// <summary>
    /// Visibility 상태 적용 Target.
    /// </summary>
    // ============================================================
    public interface IVisibilityTarget
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 표시 상태.
        /// </summary>
        // ------------------------------------------------------------
        bool IsVisible { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 표시 상태를 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        void SetVisible(bool visible);
    }
}
