using System;

namespace inonego.Xeri.Game
{
    // ============================================================
    /// <summary>
    /// 실행 조건의 공유 가능한 정의와 시간 범위 정규화 계약.
    /// </summary>
    // ============================================================
    [Serializable]
    public abstract class ExecutionTriggerDefinition
    {

    #region 생성·정규화

        // ------------------------------------------------------------
        /// <summary>
        /// 공유 정의로부터 독립적인 실행 조건 인스턴스를 생성한다.
        /// </summary>
        // ------------------------------------------------------------
        public abstract ExecutionTrigger CreateTrigger();

        // ------------------------------------------------------------
        /// <summary>
        /// 실행의 최대 시간에 맞게 작성된 조건 값을 보정한다.
        /// </summary>
        // ------------------------------------------------------------
        public virtual void Normalize(float maximumDuration)
        {
            // NONE
        }

    #endregion

    }

    // ======================================================================
    /// <summary>
    /// <br/>실행별 조건 평가 상태를 소유하는 추상 Trigger.
    /// <br/>참인 경우 effectiveTime은 충족된 시각이나 교차 구간의 시작점이다.
    /// </summary>
    // ======================================================================
    public abstract class ExecutionTrigger
    {

    #region 실행 수명과 평가

        // ------------------------------------------------------------
        /// <summary>
        /// 시작 또는 재시작 시 한 번 발생하는 조건의 상태를 초기화한다.
        /// </summary>
        // ------------------------------------------------------------
        public virtual void Begin()
        {
            // NONE
        }

        // ----------------------------------------------------------------------
        /// <summary>
        /// <br/>Begin에 대응해 Trigger가 소유한 실행별 자원을 정리한다.
        /// <br/>소유 Behavior가 종료될 때 호출하며 외부 구독은 구현자가 해제한다.
        /// </summary>
        // ----------------------------------------------------------------------
        public virtual void End()
        {
            // NONE
        }

        // ------------------------------------------------------------
        /// <summary>
        /// 조건 평가에 사용할 외부 실행 신호와 발생 시각을 수신한다.
        /// </summary>
        // ------------------------------------------------------------
        public virtual void Signal(in ExecutionSignal signal, float time)
        {
            // NONE
        }

        // ------------------------------------------------------------
        /// <summary>
        /// <br/>유효한 순방향 또는 동일 시각 구간에서 실행 조건을 평가한다.
        /// <br/>충족되지 않으면 effectiveTime 값은 의미를 갖지 않는다.
        /// </summary>
        // ------------------------------------------------------------
        public abstract bool TryEvaluate
        (
            float previousTime,
            float currentTime,
            out float effectiveTime
        );

    #endregion

    }
}
