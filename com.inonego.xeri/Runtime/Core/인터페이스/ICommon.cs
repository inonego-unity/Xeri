# 설명
IHasName과 IKeyable을 한 파일에 모은 공통 식별자 인터페이스.
파편화 방지를 위해 이름·키 관련 인터페이스를 함께 관리한다.
========================================================================= BLOCK_HEADER_END */

using System;

namespace inonego.Xeri
{
    // ============================================================
    /// <summary>
    /// 이름을 가질 수 있는 객체를 위한 인터페이스.
    /// </summary>
    // ============================================================
    public interface IHasName
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 객체의 표시 이름.
        /// </summary>
        // ------------------------------------------------------------
        public string Name { get; }
    }

    // ============================================================
    /// <summary>
    /// 키를 가질 수 있는 객체를 위한 인터페이스.
    /// </summary>
    // ============================================================
    public interface IKeyable<TKey>
    where TKey : IEquatable<TKey>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 서로 다른 객체끼리 구분하기 위한 키.
        /// </summary>
        // ------------------------------------------------------------
        public TKey Key { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 키가 설정되어 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool HasKey { get; }
    }
}
