using System;

namespace inonego.Xeri.Game.Controller
{
    // ============================================================
    /// <summary>
    /// 점프 이벤트 인수입니다.
    /// </summary>
    // ============================================================
    [Serializable]
    public struct JumpEventArgs
    {
        public int MaxCount;
        public int Count;
    }

    // ============================================================
    /// <summary>
    /// 점프 기능의 인터페이스입니다.
    /// </summary>
    // ============================================================
    public interface IJumper
    {

    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// 최대 점프 횟수입니다.
        /// </summary>
        // ------------------------------------------------------------
        public int MaxCount { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 남은 점프 횟수입니다.
        /// </summary>
        // ------------------------------------------------------------
        public int Count { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 코요테 점프 지속 시간입니다.
        /// </summary>
        // ------------------------------------------------------------
        public float CoyoteJumpDuration { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 점프 버퍼 지속 시간입니다.
        /// </summary>
        // ------------------------------------------------------------
        public float JumpBufferDuration { get; set; }

    #endregion

    #region 이벤트

        // ------------------------------------------------------------
        /// <summary>
        /// 점프가 시작될 때 호출되는 이벤트입니다.
        /// </summary>
        // ------------------------------------------------------------
        public event EventHandler<JumpEventArgs> OnJump;

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 점프를 실행하도록 트리거합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void Trigger();

        // ------------------------------------------------------------
        /// <summary>
        /// 업데이트를 진행합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void FixedUpdate();

        // ------------------------------------------------------------
        /// <summary>
        /// 업데이트를 진행합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void FixedUpdate(float fixedDeltaTime);

        // ------------------------------------------------------------
        /// <summary>
        /// 점프 카운트를 초기화합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void Reset();

    #endregion

    }
}
