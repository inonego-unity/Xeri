using System;

namespace inonego.Xeri.Utility
{
   // ============================================================
   /// <summary>
   /// 읽기 전용 페이징 상태 계약.
   /// </summary>
   // ============================================================
   public interface IReadOnlyPaginator
   {

   #region 필드

      // ------------------------------------------------------------
      /// <summary>
      /// 전체 아이템 개수.
      /// </summary>
      // ------------------------------------------------------------
      public int TotalCount { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 한 페이지에 표시할 아이템 개수.
      /// </summary>
      // ------------------------------------------------------------
      public int PerPage { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 현재 페이지 index. 0부터 시작한다.
      /// </summary>
      // ------------------------------------------------------------
      public int PageIndex { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// UI 표시용 현재 페이지 번호. 1부터 시작하며 빈 목록이면 0이다.
      /// </summary>
      // ------------------------------------------------------------
      public int PageNumber { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 전체 페이지 개수.
      /// </summary>
      // ------------------------------------------------------------
      public int PageCount { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 표시할 아이템이 없는지 여부.
      /// </summary>
      // ------------------------------------------------------------
      public bool IsEmpty { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 첫 페이지로 이동할 수 있는지 여부.
      /// </summary>
      // ------------------------------------------------------------
      public bool CanMoveFirst { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 이전 페이지로 이동할 수 있는지 여부.
      /// </summary>
      // ------------------------------------------------------------
      public bool CanMovePrev { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 다음 페이지로 이동할 수 있는지 여부.
      /// </summary>
      // ------------------------------------------------------------
      public bool CanMoveNext { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 마지막 페이지로 이동할 수 있는지 여부.
      /// </summary>
      // ------------------------------------------------------------
      public bool CanMoveLast { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 현재 페이지의 0-based 범위를 반환한다.
      /// </summary>
      // ------------------------------------------------------------
      public PageRange Range { get; }

   #endregion

   #region 이벤트

      // ------------------------------------------------------------
      /// <summary>
      /// 관찰 가능한 페이징 상태가 변경될 때 발생한다.
      /// </summary>
      // ------------------------------------------------------------
      public event EventHandler OnChange;

      // ------------------------------------------------------------
      /// <summary>
      /// 전체 아이템 개수가 변경될 때 발생한다.
      /// </summary>
      // ------------------------------------------------------------
      public event ValueChangeEventHandler<int> OnTotalCountChange;

      // ------------------------------------------------------------
      /// <summary>
      /// 한 페이지에 표시할 아이템 개수가 변경될 때 발생한다.
      /// </summary>
      // ------------------------------------------------------------
      public event ValueChangeEventHandler<int> OnPerPageChange;

      // ------------------------------------------------------------
      /// <summary>
      /// 현재 페이지 index가 변경될 때 발생한다.
      /// </summary>
      // ------------------------------------------------------------
      public event ValueChangeEventHandler<int> OnPageIndexChange;

   #endregion

   }
}
