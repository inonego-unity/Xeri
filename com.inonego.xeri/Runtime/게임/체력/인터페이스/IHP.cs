# 설명
HP 변경 가능 인터페이스 모음.

- IHP            : 생/사 상태 변경(값 타입 무관).
- IHP<TValue>    : 값까지 변경 가능.
========================================================================= BLOCK_HEADER_END */

namespace inonego.Xeri.Game
{
    // ============================================================
    /// <summary>
    /// HP 변경 가능 인터페이스 (값 타입 무관, 상태 변경만).
    /// </summary>
    // ============================================================
    public interface IHP : IReadOnlyHP
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 상태를 살아있는 상태로 설정한다.
        /// </summary>
        // ------------------------------------------------------------
        void MakeAlive(bool autoChangeValue = true);

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 상태를 죽어있는 상태로 설정한다.
        /// </summary>
        // ------------------------------------------------------------
        void MakeDead(bool autoChangeValue = true);
    }

    // ============================================================
    /// <summary>
    /// HP 변경 가능 인터페이스 (값 포함).
    /// </summary>
    // ============================================================
    public interface IHP<TValue> : IHP, IReadOnlyHP<TValue>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 체력 값. 외부에는 TValue 로 노출된다.
        /// </summary>
        // ------------------------------------------------------------
        new TValue Value { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 최대 체력 값. 외부에는 TValue 로 노출된다.
        /// </summary>
        // ------------------------------------------------------------
        new TValue MaxValue { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 힐(체력 회복)을 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        void ApplyHeal(TValue amount);

        // ------------------------------------------------------------
        /// <summary>
        /// 데미지(체력 감소)를 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        void ApplyDamage(TValue amount);
    }
}
