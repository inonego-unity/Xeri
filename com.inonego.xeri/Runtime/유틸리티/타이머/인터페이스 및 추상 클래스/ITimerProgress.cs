using System;

using TValue = System.Single;

namespace inonego.Xeri.Utility
{
    // ============================================================
    /// <summary>
    /// 타이머의 진행 상태와 시간 값을 읽는 인터페이스.
    /// </summary>
    // ============================================================
    public interface ITimerProgress
    {

    #region 상태

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머가 실행 중인지 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool IsRunning { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머가 일시정지 중인지 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool IsPaused { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 타이머 상태.
        /// </summary>
        // ------------------------------------------------------------
        public TimerState Current { get; }

    #endregion

    #region 시간

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머 지속 시간.
        /// </summary>
        // ------------------------------------------------------------
        public TValue Duration { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머가 경과한 시간.
        /// </summary>
        // ------------------------------------------------------------
        public TValue ElapsedTime { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 타이머의 남은 시간.
        /// </summary>
        // ------------------------------------------------------------
        public TValue RemainingTime { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 경과 시간 비율 (0.0 ~ 1.0).
        /// </summary>
        // ------------------------------------------------------------
        public TValue ElapsedTime01 { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 잔여 시간 비율 (0.0 ~ 1.0).
        /// </summary>
        // ------------------------------------------------------------
        public TValue RemainingTime01 { get; }

    #endregion

    }
}
