# 설명
이름 붙은 string/int/float/flag 값을 조회만 하는 인터페이스. 변경과 관찰(이벤트)은 노출하지 않는다.
IReadOnlyValueRegistry는 여기에 변경 관찰을 더한다.

# 특이사항, 제약사항
조회 컬렉션은 원본을 그대로 보여 주는 읽기 전용 뷰다. 값이 바뀌면 같은 뷰에서 바로 보인다.
========================================================================= BLOCK_HEADER_END */

using System;
using System.Collections;
using System.Collections.Generic;

namespace inonego.Xeri.Serializable
{
    // ============================================================
    /// <summary>
    /// 이름 붙은 값과 Flag를 조회하는 인터페이스.
    /// </summary>
    // ============================================================
    public interface IValueLookup
    {

    #region 컬렉션

        // ------------------------------------------------------------
        /// <summary>
        /// string 값의 읽기 전용 뷰.
        /// </summary>
        // ------------------------------------------------------------
        public IReadOnlyDictionary<string, string> ValSs { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// int 값의 읽기 전용 뷰.
        /// </summary>
        // ------------------------------------------------------------
        public IReadOnlyDictionary<string, int> ValIs { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// float 값의 읽기 전용 뷰.
        /// </summary>
        // ------------------------------------------------------------
        public IReadOnlyDictionary<string, float> ValFs { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 설정된 Flag Key의 읽기 전용 뷰.
        /// </summary>
        // ------------------------------------------------------------
        public IReadOnlyCollection<string> ValFlags { get; }

    #endregion

    #region 조회

        // ------------------------------------------------------------
        /// <summary>
        /// 어느 타입이든 Key가 존재하는지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        public bool Has(string key);

        // ------------------------------------------------------------
        /// <summary>
        /// string 값이 존재하는지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        public bool HasS(string key);

        // ------------------------------------------------------------
        /// <summary>
        /// string 값을 가져오고, 없으면 fallbackValue를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        public string GetS(string key, string fallbackValue = "");

        // ------------------------------------------------------------
        /// <summary>
        /// int 값이 존재하는지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        public bool HasI(string key);

        // ------------------------------------------------------------
        /// <summary>
        /// int 값을 가져오고, 없으면 fallbackValue를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        public int GetI(string key, int fallbackValue = 0);

        // ------------------------------------------------------------
        /// <summary>
        /// float 값이 존재하는지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        public bool HasF(string key);

        // ------------------------------------------------------------
        /// <summary>
        /// float 값을 가져오고, 없으면 fallbackValue를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        public float GetF(string key, float fallbackValue = 0f);

        // ------------------------------------------------------------
        /// <summary>
        /// Flag가 설정되어 있는지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        public bool HasFlag(string key);

    #endregion

    }
}
