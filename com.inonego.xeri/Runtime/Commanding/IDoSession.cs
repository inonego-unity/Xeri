using System;

namespace inonego.Xeri.Commanding
{
    // ============================================================
    /// <summary>
    /// DI, 테스트, mocking을 위한 DoSession 핵심 계약.
    /// </summary>
    // ============================================================
    public interface IDoSession
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 명령을 실행하고 Undo history에 기록한다.
        /// </summary>
        // ------------------------------------------------------------
        void Do(IDoCommand command);

        // ------------------------------------------------------------
        /// <summary>
        /// 마지막 명령을 실행 취소하고 성공 여부를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        bool Undo();

        // ------------------------------------------------------------
        /// <summary>
        /// 마지막 실행 취소 명령을 다시 실행하고 성공 여부를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        bool Redo();

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 Undo가 가능한지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool CanUndo { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 Redo가 가능한지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool CanRedo { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// history가 변경될 때 발생한다.
        /// </summary>
        // ------------------------------------------------------------
        event Action OnChange;
    }
}
