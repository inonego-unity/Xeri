namespace inonego.Xeri.Game
{
    // ============================================================
    /// <summary>
    /// 후보의 점수를 계산하거나 평가 실패를 보고한다.
    /// </summary>
    // ============================================================
    public interface ITargetScorer<TCandidate>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 평가 성공 시 점수를 출력하고 평가할 수 없으면 false를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        bool TryScore(in TCandidate candidate, out float score);
    }
}
