namespace inonego.Xeri.Game
{
    // ============================================================
    /// <summary>
    /// 상태 머신의 상태 인터페이스.
    /// </summary>
    // ============================================================
    public interface IState
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 상태 진입 시 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        void OnEnter();

        // ------------------------------------------------------------
        /// <summary>
        /// 상태 종료 시 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        void OnExit();

        // ------------------------------------------------------------
        /// <summary>
        /// 상태 갱신 시 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        void OnUpdate();
    }
}
