using System;

namespace inonego.Xeri.Workspace.Document
{
   // ================================================================================================
   /// <summary>
   /// <br/> Workspace에서 문서를 열거나 저장할 수 있는 위치의 최소 인터페이스.
   /// <br/> Equality는 기본 Open 흐름에서 이미 열린 session을 찾기 위한 location 동일성 기준이다.
   /// </summary>
   // ================================================================================================
   public interface IDocumentLocation : IEquatable<IDocumentLocation>
   {
      // ------------------------------------------------------------
      /// <summary>
      /// 사용자에게 표시하거나 진단에 사용할 location 이름.
      /// </summary>
      // ------------------------------------------------------------
      string Name { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// Location을 recovery record로 만든다. 기본 복구를 지원하지 않으면 null을 반환한다.
      /// </summary>
      // ------------------------------------------------------------
      IDocumentLocationRecord Record();
   }
}
