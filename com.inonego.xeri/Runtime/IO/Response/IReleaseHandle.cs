using System;

namespace inonego.Xeri.IO
{
   // ============================================================
   /// <summary>
   /// IO response가 전달하는 release 책임 handle.
   /// </summary>
   // ============================================================
   public interface IReleaseHandle : IDisposable
   {
      // ------------------------------------------------------------
      /// <summary>
      /// handle이 이미 release 되었는지 여부.
      /// </summary>
      // ------------------------------------------------------------
      bool IsReleased { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// handle이 보관하는 외부 리소스 사용 권한을 반환한다.
      /// </summary>
      // ------------------------------------------------------------
      void Release();
   }
}
