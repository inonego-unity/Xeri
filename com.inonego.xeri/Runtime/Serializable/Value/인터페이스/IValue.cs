namespace inonego.Xeri.Serializable
{
    using Primitive; // inonego.Xeri.Primitive

    // ============================================================
    /// <summary>
    /// Value 읽기 전용 뷰 인터페이스.
    /// </summary>
    // ============================================================
    public interface IReadOnlyValue<T> : IValueGetter<T>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 값.
        /// </summary>
        // ------------------------------------------------------------
        T Base { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 값이 변경될 때 발생하는 이벤트.
        /// </summary>
        // ------------------------------------------------------------
        event ValueChangeEventHandler<T> OnBaseChange;

        // ------------------------------------------------------------
        /// <summary>
        /// IValueGetter 기본 구현. Base 를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        T IValueGetter<T>.Get() => Base;
    }

    // ============================================================
    /// <summary>
    /// Value 변경 가능 인터페이스.
    /// </summary>
    // ============================================================
    public interface IValue<T> : IReadOnlyValue<T>, IValueSetter<T>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 값.
        /// </summary>
        // ------------------------------------------------------------
        new T Base { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 값을 설정한다. invokeEvent=false 면 이벤트를 발행하지 않는다.
        /// </summary>
        // ------------------------------------------------------------
        void Set(T value, bool invokeEvent = true);

        // -------------------------------------------------------------------
        /// <summary>
        /// IValueSetter 기본 구현. Set(value, invokeEvent: true) 에 위임한다.
        /// </summary>
        // -------------------------------------------------------------------
        void IValueSetter<T>.Set(T value) => Set(value, invokeEvent: true);
    }
}
