namespace inonego.Xeri.Serializable
{
   // ============================================================
   /// <summary>
   /// 객체와 문자열 사이의 직렬화 변환 인터페이스.
   /// </summary>
   // ============================================================
   public interface ISerializer
   {
      // ------------------------------------------------------------
      /// <summary>
      /// 객체를 문자열로 직렬화한다.
      /// </summary>
      // ------------------------------------------------------------
      string Serialize<T>(T value);

      // ------------------------------------------------------------
      /// <summary>
      /// 문자열에서 객체를 역직렬화한다.
      /// </summary>
      // ------------------------------------------------------------
      T Deserialize<T>(string text);
   }
}
