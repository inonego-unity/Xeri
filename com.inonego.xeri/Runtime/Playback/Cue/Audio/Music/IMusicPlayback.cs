namespace inonego.Xeri.Playback
{
    // ============================================================
    /// <summary>
    /// 같은 Timeline을 공유하는 Music Layer Group Playback.
    /// </summary>
    // ============================================================
    public interface IMusicPlayback : ICuePlayback
    {

    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// Group 재생 위치와 상태를 대표하는 Clock.
        /// </summary>
        // ------------------------------------------------------------
        IPlaybackClock Clock { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// Group에 포함된 Layer 수.
        /// </summary>
        // ------------------------------------------------------------
        int LayerCount { get; }

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 지정 Layer의 현재 개별 Volume을 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        float GetLayerVolume(int index);

        // ------------------------------------------------------------
        /// <summary>
        /// 지정 Layer의 개별 Volume을 변경한다.
        /// </summary>
        // ------------------------------------------------------------
        void SetLayerVolume(int index, float volume);

        // ------------------------------------------------------------
        /// <summary>
        /// 모든 Layer의 현재 위치를 보존하고 재생을 일시정지한다.
        /// </summary>
        // ------------------------------------------------------------
        void Pause();

        // ------------------------------------------------------------
        /// <summary>
        /// 일시정지된 모든 Layer를 같은 Timeline에서 재개한다.
        /// </summary>
        // ------------------------------------------------------------
        void Resume();

    #endregion

    }
}
