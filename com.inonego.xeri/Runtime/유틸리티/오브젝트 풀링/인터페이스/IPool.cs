using System;
using System.Collections;
using System.Collections.Generic;

using UnityEngine;

namespace inonego.Xeri.Pool
{

    // ==========================================================================================
    /// <summary>
    /// <br/> 오브젝트 풀링을 위한 인터페이스입니다.
    /// <br/> 아이템 소유권은 Equals 값 동등성이 아니라 인스턴스 참조 동일성을 기준으로 구분합니다.
    /// <br/> 풀 사이의 인계 메서드는 정상 반환 시 대상이 소유권을 소비한 것으로 간주합니다.
    /// <br/> 인계 메서드가 예외를 던지면 대상은 전달받은 아이템의 소유권을 소비하지 않아야 합니다.
    /// </summary>
    // ==========================================================================================
    public interface IPool
    {
        // NONE
    }

    // ============================================================
    /// <summary>
    /// 오브젝트 풀링을 위한 인터페이스입니다.
    /// </summary>
    // ============================================================
    public interface IPool<T> : IPool where T : class
    {

    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// 풀에 남아있는 오브젝트 목록입니다.
        /// </summary>
        // ------------------------------------------------------------
        public IReadOnlyCollection<T> Released { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 풀에 사용중인 오브젝트 목록입니다.
        /// </summary>
        // ------------------------------------------------------------
        public IReadOnlyCollection<T> Acquired { get; }

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 풀에 오브젝트가 사용중인지 여부를 반환합니다.
        /// </summary>
        // ------------------------------------------------------------
        public bool IsAcquired(T item);

        // ------------------------------------------------------------
        /// <summary>
        /// 풀에 오브젝트가 반환된 상태인지 여부를 반환합니다.
        /// </summary>
        // ------------------------------------------------------------
        public bool IsReleased(T item);

        // ------------------------------------------------------------
        /// <summary>
        /// 풀에서 오브젝트를 가져옵니다.
        /// </summary>
        // ------------------------------------------------------------
        public T Acquire();

        // ------------------------------------------------------------
        /// <summary>
        /// <br/> 풀에서 오브젝트를 비동기로 가져옵니다.
        /// <br/> 구현은 같은 풀의 동시 Acquire 지원 여부를 명시해야 합니다.
        /// </summary>
        // ------------------------------------------------------------
        public Awaitable<T> AcquireAsync();

        // ------------------------------------------------------------
        /// <summary>
        /// 풀에 오브젝트를 반환합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void Release(T item, bool pushToReleased = true);

        // ------------------------------------------------------------
        /// <summary>
        /// 풀에 있는 모든 오브젝트를 반환합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void ReleaseAll(bool pushToReleased = true);

        // ----------------------------------------------------------------------
        /// <summary>
        /// <br/> 오브젝트를 풀에 추가합니다.
        /// <br/> 정상 반환 시 Released 소유권을 소비하고, 예외 시 소비하지 않아야 합니다.
        /// </summary>
        // ----------------------------------------------------------------------
        public void PushToReleased(T item);

        // ----------------------------------------------------------------------
        /// <summary>
        /// <br/> 풀에 남아있는 오브젝트를 풀에서 제거하고 반환합니다.
        /// <br/> 풀에 남아있는 오브젝트가 없으면 새로운 오브젝트를 생성하여 반환합니다.
        /// </summary>
        // ----------------------------------------------------------------------
        public T PopFromReleased();

        // ----------------------------------------------------------------------
        /// <summary>
        /// <br/> 풀에 남아있는 오브젝트를 풀에서 제거하고 비동기로 반환합니다.
        /// <br/> 풀에 남아있는 오브젝트가 없으면 새로운 오브젝트를 생성하여 반환합니다.
        /// </summary>
        // ----------------------------------------------------------------------
        public Awaitable<T> PopFromReleasedAsync();

        // ------------------------------------------------------------
        /// <summary>
        /// <br/> Acquired된 아이템을 다른 풀의 Acquired로 이동합니다.
        /// <br/> 대상이 인계를 거절하면 원본 풀은 기존 소유권을 유지해야 합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void MoveAcquiredOneTo(IPool<T> other, T item);

        // ----------------------------------------------------------------------
        /// <summary>
        /// <br/> Released된 아이템을 다른 풀의 Released로 이동합니다.
        /// <br/> 풀에 남아있는 오브젝트가 없으면 새로운 오브젝트를 생성하여 이동합니다.
        /// <br/> 대상이 인계를 거절하면 원본 풀은 인계 후보의 소유권을 유지해야 합니다.
        /// </summary>
        // ----------------------------------------------------------------------
        public void MoveReleasedOneTo(IPool<T> other);

        // ------------------------------------------------------------
        /// <summary>
        /// <br/> 아이템을 풀의 Acquired 소유권으로 인계합니다.
        /// <br/> 정상 반환 시 소유권을 소비하고, 예외 시 소비하지 않아야 합니다.
        /// </summary>
        // ------------------------------------------------------------
        protected internal void AcquireInternal(T item);

    #endregion

    }
}
