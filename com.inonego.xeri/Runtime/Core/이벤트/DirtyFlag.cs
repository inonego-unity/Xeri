using System;

using UnityEngine;

namespace inonego.Xeri
{
    // ============================================================
    /// <summary>
    /// 읽기 전용 더티 플래그 인터페이스.
    /// </summary>
    // ============================================================
    public interface IDirtyFlag
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 더티 플래그가 설정되어 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsDirty { get; }
    }

    // ============================================================
    /// <summary>
    /// 더티 플래그 구현체.
    /// </summary>
    // ============================================================
    [Serializable]
    public class DirtyFlag : IDirtyFlag
    {

    #region 필드

        [SerializeField]
        private bool isDirty = false;

        // ------------------------------------------------------------
        /// <summary>
        /// 더티 플래그가 설정되어 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool IsDirty => isDirty;

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 더티 플래그를 설정한다.
        /// </summary>
        // ------------------------------------------------------------
        public void SetDirty() => isDirty = true;

        // ------------------------------------------------------------
        /// <summary>
        /// 더티 플래그를 해제한다.
        /// </summary>
        // ------------------------------------------------------------
        public void Clear() => isDirty = false;

    #endregion

    }
}
