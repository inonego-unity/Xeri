using System;
using System.Collections;
using System.Collections.Generic;

namespace inonego.Xeri.UI.TableGrid
{
    // ============================================================
    /// <summary>
    /// 클립보드 계획의 공통 결과(건너뛴 셀 수와 실패 이유).
    /// </summary>
    // ============================================================
    internal abstract class TableGridClipPlan
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 읽기 전용이거나 그 값을 받지 않는 열이라 조용히 건너뛴 셀 수.
        /// </summary>
        // ------------------------------------------------------------
        public int ReadOnly { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 값이 열 형식에 맞지 않아 건너뛴 셀 수.
        /// </summary>
        // ------------------------------------------------------------
        public int Invalid { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 표 범위 밖이라 건너뛴 셀 수.
        /// </summary>
        // ------------------------------------------------------------
        public int Outside { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 계획을 만들 수 없던 이유. 만들었으면 null이다.
        /// </summary>
        // ------------------------------------------------------------
        public string Error { get; set; }

        // ----------------------------------------------------------------------
        /// <summary>
        /// <br/> 상태 줄에 보일 결과 문구. head 뒤에 맞지 않는 값·범위 밖 셀 수를 잇는다.
        /// <br/> 읽기 전용으로 건너뛴 셀은 의도한 동작이라 넣지 않는다.
        /// </summary>
        // ----------------------------------------------------------------------
        public string Describe(string head)
        {
            var parts = new List<string>
            {
                head,
            };
            if (Invalid > 0)
            {
                parts.Add($"맞지 않는 값 {Invalid:N0}셀");
            }

            if (Outside > 0)
            {
                parts.Add($"범위 밖 {Outside:N0}셀");
            }

            return string.Join(" · ", parts);
        }
    }

    // ============================================================
    /// <summary>
    /// 클립보드·지우기로 만든 셀 변경 계획.
    /// </summary>
    // ============================================================
    internal sealed class TableGridEditPlan : TableGridClipPlan
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 호스트에 요청할 셀 변경.
        /// </summary>
        // ------------------------------------------------------------
        public List<TableGridEditIntent> Edits { get; } = new();

        // ----------------------------------------------------------------------
        /// <summary>
        /// 잘못된 값으로 건너뛴 셀. 잠깐 강조한다. 읽기 전용으로 건너뛴 셀은 넣지 않는다.
        /// </summary>
        // ----------------------------------------------------------------------
        public List<TableGridCellAddress> Rejected { get; } = new();

        // ------------------------------------------------------------
        /// <summary>
        /// 붙여넣기 결과 요약.
        /// </summary>
        // ------------------------------------------------------------
        public TableGridPasteFeedback ToFeedback()
        {
            return new TableGridPasteFeedback(ReadOnly, Invalid, Outside);
        }
    }

    // ============================================================
    /// <summary>
    /// 클립보드 행을 새 행 값으로 바꾼 삽입 계획.
    /// </summary>
    // ============================================================
    internal sealed class TableGridInsertPlan : TableGridClipPlan
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 넣을 행마다 열 ID → 값.
        /// </summary>
        // ------------------------------------------------------------
        public List<IReadOnlyDictionary<string, object>> Rows { get; } = new();
    }
}
