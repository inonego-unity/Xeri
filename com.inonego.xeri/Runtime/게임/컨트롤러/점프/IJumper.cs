using System;

namespace inonego.Xeri.Game.Controller
{
    // ============================================================
    /// <summary>
    /// 점프 이벤트 인수입니다.
    /// </summary>
    // ============================================================
    [Serializable]
    public struct JumpEventArgs
    {
        public int MaxCount;
        public int Count;
    }

    // ============================================================
    /// <summary>
    /// 점프 기능의 인터페이스입니다.
    /// </summary>
    // ============================================================
    public interface IJumper
    {

    #region 필드

        // ------------------------------------------------------------
        /// <summary>
        /// 점프 실행이 허용된 상태인지 여부입니다.
        /// </summary>
        // ------------------------------------------------------------
        public bool IsJumpAllowed { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 최대 점프 횟수입니다.
        /// </summary>
        // ------------------------------------------------------------
        public int MaxCount { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 남은 점프 횟수입니다.
        /// </summary>
        // ------------------------------------------------------------
        public int Count { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 코요테 점프 지속 시간입니다.
        /// </summary>
        // ------------------------------------------------------------
        public float CoyoteJumpDuration { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 점프 버퍼 지속 시간입니다.
        /// </summary>
        // ------------------------------------------------------------
        public float JumpBufferDuration { get; set; }

    #endregion

    #region 이벤트

        // ------------------------------------------------------------
        /// <summary>
        /// 점프가 시작될 때 호출되는 이벤트입니다.
        /// </summary>
        // ------------------------------------------------------------
        public event EventHandler<JumpEventArgs> OnJump;

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 점프를 실행하도록 트리거합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void Trigger();

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 점프 조건이 충족되면 즉시 점프를 실행합니다.
        /// </summary>
        // ------------------------------------------------------------
        public bool TryJump();

        // ------------------------------------------------------------
        /// <summary>
        /// 실행 대기 중인 점프 요청을 취소합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void CancelPending();

        // ------------------------------------------------------------
        /// <summary>
        /// 전달받은 접지 상태를 기준으로 물리 갱신을 진행합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void FixedTick(float fixedDeltaTime, bool isGrounded);

        // ------------------------------------------------------------
        /// <summary>
        /// 점프 카운트를 초기화합니다.
        /// </summary>
        // ------------------------------------------------------------
        public void Reset();

    #endregion

    }
}
