using inonego.Xeri;

namespace inonego.Xeri.Workspace.Document
{
   // ============================================================
   /// <summary>
   /// Workspace에서 열린 문서의 작업 상태 인터페이스.
   /// </summary>
   // ============================================================
   public interface IDocumentSession
   {
      // ------------------------------------------------------------
      /// <summary>
      /// 세션이 다루는 문서 정보.
      /// </summary>
      // ------------------------------------------------------------
      IDocument Document { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 세션에서 편집 중인 문서 모델.
      /// </summary>
      // ------------------------------------------------------------
      IDocumentModel Model { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 세션이 현재 연결된 문서 location.
      /// </summary>
      // ------------------------------------------------------------
      IDocumentLocation Location { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 세션의 편집 내용이 저장 대상과 달라졌는지 여부.
      /// </summary>
      // ------------------------------------------------------------
      bool IsDirty { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 세션의 문서 정보가 변경될 때 발생한다.
      /// </summary>
      // ------------------------------------------------------------
      event ValueChangeEventHandler<IDocument> OnDocumentChange;

      // ------------------------------------------------------------
      /// <summary>
      /// 세션의 문서 location이 변경될 때 발생한다.
      /// </summary>
      // ------------------------------------------------------------
      event ValueChangeEventHandler<IDocumentLocation> OnLocationChange;

      // ------------------------------------------------------------
      /// <summary>
      /// 세션의 dirty 상태가 변경될 때 발생한다.
      /// </summary>
      // ------------------------------------------------------------
      event ValueChangeEventHandler<bool> OnDirtyChange;

      // ------------------------------------------------------------
      /// <summary>
      /// 세션의 문서 정보를 설정한다.
      /// </summary>
      // ------------------------------------------------------------
      void SetDocument(IDocument document);

      // ------------------------------------------------------------
      /// <summary>
      /// 세션의 문서 location을 설정한다.
      /// </summary>
      // ------------------------------------------------------------
      void SetLocation(IDocumentLocation location);

      // ------------------------------------------------------------
      /// <summary>
      /// 세션을 변경됨 상태로 표시한다.
      /// </summary>
      // ------------------------------------------------------------
      void SetDirty();

      // ------------------------------------------------------------
      /// <summary>
      /// 세션의 변경됨 상태를 해제한다.
      /// </summary>
      // ------------------------------------------------------------
      void ClearDirty();
   }
}
