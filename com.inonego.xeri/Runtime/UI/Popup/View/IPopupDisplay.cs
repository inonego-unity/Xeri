using UnityEngine;
using UnityEngine.UIElements;

namespace inonego.Xeri.UI
{
    // ============================================================
    /// <summary>
    /// Popup 단계를 표시하고 좌표를 변환하는 계약.
    /// </summary>
    // ============================================================
    internal interface IPopupDisplay
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 팝업을 놓을 수 있는 팝업 좌표계의 영역.
        /// </summary>
        // ------------------------------------------------------------
        Rect WorkArea { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 소유 패널의 월드 좌표를 팝업 좌표계로 변환한다.
        /// </summary>
        // ------------------------------------------------------------
        Vector2 ToPopupPosition(Vector2 worldPosition);

        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 깊이의 팝업이 실제로 놓인 경계를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        Rect GetBounds(int depth);

        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 경계에 팝업 단계를 열고 내용을 담을 컨테이너를 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        VisualElement OpenLevel(int depth, Rect bounds);

        // ------------------------------------------------------------
        /// <summary>
        /// 지정한 깊이 이상에 해당하는 팝업 단계를 모두 닫는다.
        /// </summary>
        // ------------------------------------------------------------
        void CloseFrom(int depth);

        // ------------------------------------------------------------
        /// <summary>
        /// 모든 팝업 단계와 표시 자원을 정리한다.
        /// </summary>
        // ------------------------------------------------------------
        void Close();
    }
}
