using System;

namespace inonego.Xeri.Serializable
{
    // ============================================================
    /// <summary>
    /// 값을 수정하고 상태 변경을 알리는 수정자 인터페이스.
    /// </summary>
    // ============================================================
    public interface IModifier<T>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// Modify 결과에 영향을 주는 내부 상태가 변경된 뒤 발생한다.
        /// </summary>
        // ------------------------------------------------------------
        event Action OnChange;

        // ------------------------------------------------------------
        /// <summary>
        /// 수정자가 값을 수정하여 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        public T Modify(T value);
    }
}
