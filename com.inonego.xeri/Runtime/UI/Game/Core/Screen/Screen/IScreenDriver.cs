namespace inonego.Xeri.UI.Game
{
    // ============================================================
    /// <summary>
    /// Screen 표시 backend 계약.
    /// </summary>
    // ============================================================
    public interface IScreenDriver : IPresentationTransitionTarget
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 Screen 표시 진행 값.
        /// </summary>
        // ------------------------------------------------------------
        float Visibility { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// backend가 제공하는 기본 Focus 대상.
        /// </summary>
        // ------------------------------------------------------------
        object DefaultFocus { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 지정 Focus 대상이 이 Screen 표시 범위에 속하는지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        bool ContainsFocus(object target);

        // ------------------------------------------------------------
        /// <summary>
        /// Screen Root 활성 상태를 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        void SetVisible(bool visible);

        // ------------------------------------------------------------
        /// <summary>
        /// Screen 상호작용 가능 상태를 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        void SetInteractable(bool interactable);
    }
}
