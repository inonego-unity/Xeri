# 설명
CollectionEditorView가 사용하는 직렬화 컬렉션 편집 모델 계약을 정의한다.
Model이 source row 해석, type-aware Add 대상, validation, mutation 및 invariant 복구를 소유한다.
편집창 수명과 검색 표시 문자열은 View 책임으로 유지한다.
