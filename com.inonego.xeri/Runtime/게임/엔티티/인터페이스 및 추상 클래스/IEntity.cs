namespace inonego.Xeri.Game
{
    using Xeri.Serializable;

    // ============================================================
    /// <summary>
    /// 엔티티 읽기 전용 뷰 인터페이스.
    /// </summary>
    // ============================================================
    public interface IReadOnlyEntity : IKeyable<ulong>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 체력 상태(읽기 전용, 값 타입 무관).
        /// </summary>
        // ------------------------------------------------------------
        IReadOnlyHP HP { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 그룹 인덱스(읽기 전용).
        /// </summary>
        // ------------------------------------------------------------
        IReadOnlyValue<int> Group { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 스폰되어 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsSpawned { get; }
    }

    // ======================================================================
    /// <summary>
    /// 시스템 내부 엔티티 인터페이스. SpawnRegistry 등록 가능 + HP/Group mutable.
    /// </summary>
    // ======================================================================
    public interface IEntity : IReadOnlyEntity, ISpawnRegistryObject<ulong>
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 체력(시스템 내부 mutable 노출). IReadOnlyEntity.HP 를 가린다.
        /// </summary>
        // ------------------------------------------------------------
        new IHP HP { get; }

        // ----------------------------------------------------------------------
        /// <summary>
        /// 그룹 인덱스(시스템 내부 mutable 노출). IReadOnlyEntity.Group 을 가린다.
        /// </summary>
        // ----------------------------------------------------------------------
        new IValue<int> Group { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 키를 설정한다. 레지스트리 내부에서만 호출.
        /// </summary>
        // ------------------------------------------------------------
        protected internal void SetKey(ulong key);

        // ------------------------------------------------------------
        /// <summary>
        /// 키를 초기화한다. 레지스트리 내부에서만 호출.
        /// </summary>
        // ------------------------------------------------------------
        protected internal void ClearKey();
    }
}
