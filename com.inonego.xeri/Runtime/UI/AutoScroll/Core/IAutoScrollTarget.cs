using UnityEngine;

namespace inonego.Xeri.UI.AutoScroll
{
    // ============================================================
    /// <summary>
    /// 자동 스크롤 대상.
    /// </summary>
    // ============================================================
    public interface IAutoScrollTarget
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 스크롤 위치를 delta만큼 옮긴다. 실제로 움직였으면 true다.
        /// </summary>
        // ------------------------------------------------------------
        bool ScrollBy(Vector2 delta);
    }
}
