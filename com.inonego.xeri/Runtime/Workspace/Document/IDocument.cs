namespace inonego.Xeri.Workspace.Document
{
   // ============================================================
   /// <summary>
   /// Workspace에서 관리되는 문서의 최소 설명 인터페이스.
   /// </summary>
   // ============================================================
   public interface IDocument
   {
      // ------------------------------------------------------------
      /// <summary>
      /// 문서 종류 식별자.
      /// </summary>
      // ------------------------------------------------------------
      string TypeID { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 문서 스키마 또는 형식 버전.
      /// </summary>
      // ------------------------------------------------------------
      string Version { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 사용자에게 표시할 문서 이름.
      /// </summary>
      // ------------------------------------------------------------
      string Name { get; }
   }
}
