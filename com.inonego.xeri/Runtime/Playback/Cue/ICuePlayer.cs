namespace inonego.Xeri.Playback
{
    // ============================================================
    /// <summary>
    /// 특정 Cue 타입을 실행하는 Player.
    /// </summary>
    // ============================================================
    public interface ICuePlayer
    {
    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 지정 Cue를 이 Player가 처리할 수 있는지 반환한다.
        /// </summary>
        // ------------------------------------------------------------
        bool CanPlay(IPlaybackCue cue);

        // ----------------------------------------------------------------------
        /// <summary>
        /// <br/> Cue를 실행하고 해당 실행의 종료 책임을 반환한다.
        /// <br/> 실행이 실패하면 Player가 부분 생성 자원을 직접 정리한 뒤 예외를 전달해야 한다.
        /// </summary>
        // ----------------------------------------------------------------------
        ICuePlayback Play(IPlaybackCue cue);

    #endregion

    }
}
